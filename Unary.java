public class Unary {
    public static void main(String[] args) {

        int a = 10;
        int b = 20;
        boolean isNumber = true;

        System.out.println(+a);
        System.out.println(-b);

        System.out.println(++a);
        System.out.println(--b);

        System.out.println(!isNumber);
    }
}
