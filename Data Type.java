public class DataType {
    public static void main(String[] args) {
        byte age = 19;//byte variable
        short salary = 30000;//short variable
        int marks = 95;//int variable
        long population = 1400000000L;//long variable
        float price = 99.5f;//float variable
        double pi = 3.14159;//double variable
        char grade = 'A'; //character variable
        boolean passed = true;//boolean variable

        System.out.println(age);
        System.out.println(salary);
        System.out.println(marks);
        System.out.println(population);
        System.out.println(price);
        System.out.println(pi);
        System.out.println(grade);
        System.out.println(passed);
    }
}

