package Operators;
public class Assignment {
    public static void main(String[]args){
        int a=10;
        System.out.println("Initial Value: "+a);
        a+=5;//a=a+5
        System.out.println("After+=: "+a);
        a-=5;//a=a-5        
        System.out.println("After-=: "+a);
        a*=5;//a=a*5
        System.out.println("After*=: "+a);
        a/=5;//a=a/5
        System.out.println("After/=: "+a);
    }
}
